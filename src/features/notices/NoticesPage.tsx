import { useMemo, useState } from "react";
import { Search } from "lucide-react";
import { Callout } from "../../components/Callout";
import { Card } from "../../components/Card";
import { PageHeader } from "../../components/PageHeader";
import notices from "../../generated/notices.json";
import "../formats/FormatsPage.css";
import "./NoticesPage.css";

interface Component {
  name: string;
  version: string;
  license: string;
  source: string;
  homepage: string | null;
}

const components = notices.components as Component[];
const needsAttention = (c: Component) => /MPL|OFL/i.test(c.license);

/** Open-source software that ships inside OrangeFile. Generated by `npm run notices`. */
export function NoticesPage() {
  const [q, setQ] = useState("");
  const shown = useMemo(() => {
    const s = q.trim().toLowerCase();
    return s ? components.filter((c) => `${c.name} ${c.license} ${c.source}`.toLowerCase().includes(s)) : components;
  }, [q]);
  const attention = components.filter(needsAttention);

  return (
    <>
      <PageHeader title="Third-party notices" subtitle="OrangeFile is built on open-source software. Here is what ships inside it, and under which licenses." />
      <Callout tone="info" title="About this list">
        It is generated from the app's dependency lists ({components.length} components). Full license texts for each package are published with its source; the installer will carry them too. The libwebp license text is included below.
      </Callout>
      {attention.length > 0 && (
        <Callout tone="warning" title="Licenses with extra conditions">
          {attention.length} components use MPL-2.0 or OFL-1.1: {attention.map((c) => c.name).join(", ")}. Their notices must stay with the app, and the source of the MPL-2.0 files must stay available.
        </Callout>
      )}
      <Card title="Native libraries">
        {notices.texts.map((t) => (
          <details key={t.name} className="license-text">
            <summary>
              {t.name} <span className="pill pill--ok">{t.license}</span>
            </summary>
            <pre className="selectable" tabIndex={0} aria-label={`${t.name} license text`}>{t.text}</pre>
          </details>
        ))}
      </Card>
      <Card
        title="All components"
        action={
          <label className="jobs-search">
            <Search size={16} aria-hidden />
            <input type="search" placeholder="Search" aria-label="Search components" value={q} onChange={(e) => setQ(e.target.value)} />
          </label>
        }
      >
        <div className="notices-scroll" tabIndex={0} role="region" aria-label="Third-party components list">
          <table className="plain-table">
            <caption className="sr-only">Third-party components</caption>
            <thead>
              <tr>
                <th scope="col">Name</th>
                <th scope="col">Version</th>
                <th scope="col">License</th>
                <th scope="col">Kind</th>
              </tr>
            </thead>
            <tbody>
              {shown.map((c) => (
                <tr key={`${c.source}-${c.name}-${c.version}`}>
                  <th scope="row" className="selectable">{c.name}</th>
                  <td className="selectable">{c.version}</td>
                  <td className="selectable">{c.license}</td>
                  <td>{c.source}</td>
                </tr>
              ))}
              {shown.length === 0 && (
                <tr>
                  <td colSpan={4}>No component matches “{q}”.</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </Card>
    </>
  );
}
